def to_arrow(frame: pd.DataFrame, schema: pa.Schema, table: str, seed: int) -> pa.Table:
    """Convert a DataFrame to an Arrow table with exactly ``schema`` and dataset metadata."""
    arrays = []
    for field in schema:
        column = frame[field.name]
        if pa.types.is_date32(field.type) and pd.api.types.is_datetime64_any_dtype(column):
            days = column.to_numpy(dtype="datetime64[s]").astype("datetime64[D]")
            arrays.append(pa.array(days, type=field.type, mask=np.isnat(days)))
        else:
            arrays.append(pa.array(column, type=field.type, from_pandas=True))
    metadata = {
        "stockpilot.synthetic": "true",
        "stockpilot.notice": NOTICE,
        "stockpilot.table": table,
        "stockpilot.generator": f"stockpilot {__version__}",
        "stockpilot.seed": str(seed),
        "stockpilot.description": TABLE_DESCRIPTIONS[table],
    }
    return pa.Table.from_arrays(arrays, schema=schema.with_metadata(metadata))


def write_table(table: pa.Table, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    pq.write_table(table, path, compression="zstd")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()
